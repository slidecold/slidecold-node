#!/usr/bin/env node
// Reads openapi.yaml and writes packages/slidecold/src/generated/*. Do not hand-edit the output.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import openapiTS, { astToString } from 'openapi-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const specPath = join(root, 'openapi.yaml');
const outDir = join(root, 'packages/slidecold/src/generated');
const spec = YAML.parse(readFileSync(specPath, 'utf8'));
const HEADER = '// Generated by scripts/generate.mjs from openapi.yaml. Do not edit.\n';

// SDK method-name overrides. Everything else is derived by stripping the resource noun from the
// operationId and a leading "get" (getCampaignStats -> stats, listAudienceMembers -> listMembers).
const METHOD_OVERRIDES = {
  sendConversationReply: 'reply',
  getAccountsProxyHealth: 'proxyHealth',
};

const resolveRef = (ref) => ref.replace(/^#\//, '').split('/').reduce((o, k) => o[k], spec);

function deref(node, seen = []) {
  if (Array.isArray(node)) return node.map((n) => deref(n, seen));
  if (!node || typeof node !== 'object') return node;
  if (node.$ref) {
    if (seen.includes(node.$ref)) return {}; // cycle guard
    const { $ref, ...rest } = node;
    return deref({ ...resolveRef($ref), ...rest }, [...seen, $ref]);
  }
  return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, deref(v, seen)]));
}

const lcFirst = (s) => s[0].toLowerCase() + s.slice(1);
const ucFirst = (s) => s[0].toUpperCase() + s.slice(1);

function methodName(operationId, tag) {
  if (METHOD_OVERRIDES[operationId]) return METHOD_OVERRIDES[operationId];
  const plural = ucFirst(tag);
  const singular = plural.replace(/ies$/, 'y').replace(/s$/, '');
  let name = operationId.replace(new RegExp(`${plural}|${singular}`), '');
  if (name.startsWith('get') && name.length > 3) name = name.slice(3);
  return lcFirst(name);
}

const ops = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const httpMethod of ['get', 'post', 'put', 'patch', 'delete']) {
    const op = item[httpMethod];
    if (!op) continue;
    const params = deref([...(item.parameters ?? []), ...(op.parameters ?? [])]);
    const tag = op.tags[0];
    const resource = lcFirst(tag);
    let body = null;
    if (op.requestBody) {
      const rb = deref(op.requestBody);
      const json = rb.content['application/json'];
      const mp = rb.content['multipart/form-data'];
      body = {
        required: !!rb.required,
        json: !!json,
        schema: json?.schema ?? null,
        multipartField: mp ? Object.keys(mp.schema.properties)[0] : null,
      };
    }
    const okKey = Object.keys(op.responses).find((c) => c.startsWith('2'));
    const okContent = deref(op.responses[okKey]).content ?? {};
    ops.push({
      operationId: op.operationId,
      resource,
      method: methodName(op.operationId, tag),
      httpMethod: httpMethod.toUpperCase(),
      path,
      pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
      queryParams: params
        .filter((p) => p.in === 'query')
        .map((p) => ({ name: p.name, required: !!p.required, description: p.description, schema: p.schema })),
      body,
      responseTypes: Object.keys(okContent),
      scope: op['x-required-scope'],
      summary: op.summary,
      description: op.description?.trim(),
    });
  }
}

// Sanity: unique operationIds and unique resource.method names.
const seen = new Set();
for (const o of ops) {
  const key = `${o.resource}.${o.method}`;
  if (seen.has(key) || seen.has(o.operationId)) throw new Error(`duplicate ${key} / ${o.operationId}`);
  seen.add(key).add(o.operationId);
}

mkdirSync(outDir, { recursive: true });

// 1. Request/response types.
const ast = await openapiTS(new URL(`file://${specPath}`));
writeFileSync(join(outDir, 'schema.ts'), HEADER + '/* eslint-disable */\n' + astToString(ast));

// 2. Operations table.
const table = Object.fromEntries(ops.map((o) => [o.operationId, o]));
writeFileSync(
  join(outDir, 'operations.ts'),
  HEADER +
    `import type { OperationDef } from '../types.js';\n\n` +
    `export type OperationId =\n${ops.map((o) => `  | '${o.operationId}'`).join('\n')};\n\n` +
    `export const operations: Record<OperationId, OperationDef> = ${JSON.stringify(table, null, 2)};\n`,
);

// 3. Resource classes.
const byResource = new Map();
for (const o of ops) byResource.set(o.resource, [...(byResource.get(o.resource) ?? []), o]);

const docComment = (o) => {
  const lines = [o.summary, '', `Scope: \`${o.scope}\` · \`${o.httpMethod} ${o.path}\``];
  if (o.description) lines.push('', ...o.description.split('\n'));
  return `  /**\n${lines.map((l) => `   *${l ? ' ' + l.replace(/\*\//g, '*\\/') : ''}`).join('\n')}\n   */\n`;
};

function methodSource(o) {
  const id = `'${o.operationId}'`;
  const args = o.pathParams.map((p) => `${p}: string`);
  const reqQuery = o.queryParams.filter((q) => q.required).map((q) => q.name);
  const optQuery = o.queryParams.filter((q) => !q.required);
  args.push(...reqQuery.map((q) => `${q}: QueryOf<${id}>['${q}']`));
  if (o.body) args.push(`body${o.body.required ? '' : '?'}: BodyOf<${id}>`);
  if (optQuery.length) {
    const t = reqQuery.length ? `Omit<QueryOf<${id}>, ${reqQuery.map((q) => `'${q}'`).join(' | ')}>` : `QueryOf<${id}>`;
    args.push(`query?: ${t}`);
  }
  args.push('options?: RequestOptions');
  const parts = [];
  if (o.pathParams.length) parts.push(`path: { ${o.pathParams.join(', ')} }`);
  if (reqQuery.length || optQuery.length) {
    parts.push(`query: { ${optQuery.length ? '...query' + (reqQuery.length ? ', ' : '') : ''}${reqQuery.join(', ')} }`);
  }
  if (o.body) parts.push('body');
  return (
    docComment(o) +
    `  ${o.method}(${args.join(', ')}): Promise<ResponseOf<${id}>> {\n` +
    `    return this._client.request(${id}, { ${parts.join(', ')} }, options);\n  }\n`
  );
}

let res = HEADER + `import type { BodyOf, QueryOf, Requester, RequestArgs, RequestOptions, ResponseOf } from '../types.js';\nimport type { OperationId } from './operations.js';\n`;
for (const [resource, list] of byResource) {
  res += `\nexport class ${ucFirst(resource)}Resource {\n  constructor(private readonly _client: Requester) {}\n\n`;
  res += list.map(methodSource).join('\n') + '}\n';
}
res += `\n/** Base class wiring every resource group to a {@link Requester}. */\nexport abstract class ResourceClient implements Requester {\n`;
for (const resource of byResource.keys()) res += `  readonly ${resource}: ${ucFirst(resource)}Resource = new ${ucFirst(resource)}Resource(this);\n`;
res += `  abstract request<K extends OperationId>(operationId: K, args?: RequestArgs, options?: RequestOptions): Promise<ResponseOf<K>>;\n}\n`;
writeFileSync(join(outDir, 'resources.ts'), res);

console.log(`Generated ${ops.length} operations in ${byResource.size} resources:`);
for (const o of ops) console.log(`  ${o.resource}.${o.method}  ${o.httpMethod} ${o.path}`);
